const makeHistory = ({
  id,
  date,
  ownerId,
  ownerName,
  stage,
  category,
  activityType,
  duration,
}) => ({
  id,
  Date: date,
  Owner: { id: ownerId, name: ownerName },
  Current_Stage: stage,
  History_Type: category,
  History_Result: activityType,
  Duration_Min: String(duration),
});

